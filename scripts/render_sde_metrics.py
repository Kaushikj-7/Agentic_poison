#!/usr/bin/env python3
"""Regenerate the AgentPOI-SDE benchmark blocks inside the published documentation.

The documented SDE metrics are produced by this script from a **live** benchmark execution
(``agentpoi_sde.eval.benchmark.run_benchmark``), never typed by hand. Each target file carries
a pair of markers::

    <!-- BEGIN SDE_BENCHMARK (generated ... ) -->
    ... generated table ...
    <!-- END SDE_BENCHMARK -->

Run with ``--check`` to verify the committed documents are in sync with the current code; the
pre-flight gate (``scripts/ci_check.py``) and ``tests/test_sde_docs_metrics.py`` both use that
mode, so a documented metric can never drift from measured behaviour.

Usage:
    python scripts/render_sde_metrics.py [--check]
"""

from __future__ import annotations

import os
import sys
from typing import Dict, List, Optional, Sequence

REPO_ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
if REPO_ROOT not in sys.path:
    sys.path.insert(0, REPO_ROOT)

from agentpoi_sde.eval.benchmark import BenchmarkReport, run_benchmark  # noqa: E402

BEGIN = "<!-- BEGIN SDE_BENCHMARK"
END = "<!-- END SDE_BENCHMARK -->"

TARGETS = (
    os.path.join(REPO_ROOT, "README.md"),
    os.path.join(REPO_ROOT, "docs", "SDE_ARCHITECTURE.md"),
)

_BEGIN_LINE = (
    BEGIN + " (generated by scripts/render_sde_metrics.py from a live benchmark run; "
    "do not edit by hand) -->"
)


def render_block(report: Optional[BenchmarkReport] = None) -> str:
    """Render the benchmark block as Markdown, from a live run."""
    report = report or run_benchmark()
    baseline = report.baseline
    defended = report.defended
    total = defended.adversarial_total + defended.clean_total
    families = len(defended.per_family)
    blocked = defended.adversarial_total - defended.adversarial_landed

    def row(label: str, metrics, strict: bool) -> str:
        bold = (lambda value: f"**{value}**") if strict else (lambda value: value)
        return (
            f"| {bold(label)} | {total} | {bold(f'{metrics.emar:.1f}%')} | "
            f"{bold(f'{metrics.ltsr:.1f}%')} | {bold(f'{metrics.cdr:.1f}%')} | "
            f"{bold(f'{metrics.avr:.1f}%')} | {bold(f'{metrics.slr:.1f}%')} | "
            f"{metrics.mean_latency_ms:.2f} ms |"
        )

    lines: List[str] = [
        _BEGIN_LINE,
        "",
        f"_Generated from a live execution of the {total}-scenario suite: "
        f"{defended.adversarial_total} adversarial mutations across {families} attack families "
        f"plus {defended.clean_total} legitimate engineering tasks, scored by a "
        f"defence-independent state-diff oracle._",
        "",
        "| Mode | Scenarios | EMAR (↓) | LTSR (↑) | CDR (↓) | AVR (↓) | SLR (↓) | Mean Latency |",
        "| :--- | :---: | :---: | :---: | :---: | :---: | :---: | :---: |",
        row("Undefended (permissive)", baseline, strict=False),
        row("AgentPOI-SDE (fail-closed)", defended, strict=True),
        "",
        f"- **Adversarial mutations landed under AgentPOI-SDE:** "
        f"{defended.adversarial_landed}/{defended.adversarial_total} "
        f"({blocked} blocked fail-closed).",
        f"- **Legitimate engineering tasks preserved:** "
        f"{defended.clean_landed}/{defended.clean_total}.",
        "- **AVR / SLR** count architecture and credential breaches in the *resulting repository "
        "state* of every landed mutation, read after execution — not from the defence's verdict.",
        "- Mean latency is machine dependent and is excluded from the documentation sync check.",
        "",
        END,
    ]
    return "\n".join(lines)


def replace_block(text: str, block: str) -> str:
    """Replace the marked region of ``text`` with ``block`` (markers included)."""
    start = text.find(BEGIN)
    end = text.find(END)
    if start == -1 or end == -1 or end < start:
        raise ValueError(
            f"missing {BEGIN!r} / {END!r} markers; add them before regenerating"
        )
    end += len(END)
    return text[:start] + block + text[end:]


def _strip_latency(text: str) -> str:
    """Drop latency cells so the sync check is independent of machine speed."""
    out: List[str] = []
    for line in text.splitlines():
        if line.startswith("|") and line.rstrip().endswith("ms |"):
            line = line.rsplit("|", 2)[0] + "| _latency_ |"
        out.append(line)
    return "\n".join(out)


def render_targets(report: Optional[BenchmarkReport] = None) -> Dict[str, str]:
    """Return the desired contents of every documentation target."""
    report = report or run_benchmark()
    block = render_block(report)
    rendered: Dict[str, str] = {}
    for path in TARGETS:
        with open(path, "r", encoding="utf-8") as handle:
            rendered[path] = replace_block(handle.read(), block)
    return rendered


def main(argv: Optional[Sequence[str]] = None) -> int:
    """Write the generated blocks, or verify they are already up to date."""
    args = list(argv if argv is not None else sys.argv[1:])
    check_only = "--check" in args

    try:
        sys.stdout.reconfigure(encoding="utf-8")
    except Exception:
        pass

    rendered = render_targets()
    stale: List[str] = []
    for path, new_text in rendered.items():
        rel = os.path.relpath(path, REPO_ROOT).replace("\\", "/")
        with open(path, "r", encoding="utf-8") as handle:
            current = handle.read()
        if _strip_latency(current) == _strip_latency(new_text):
            print(f"[ok]      {rel} is in sync with the live benchmark")
            continue
        stale.append(rel)
        if check_only:
            print(f"[STALE]   {rel} does not match live execution")
        else:
            with open(path, "w", encoding="utf-8", newline="\n") as handle:
                handle.write(new_text)
            print(f"[updated] {rel}")

    if check_only and stale:
        print(
            "\nDocumented metrics are stale. Run: python scripts/render_sde_metrics.py",
            file=sys.stderr,
        )
        return 1
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
